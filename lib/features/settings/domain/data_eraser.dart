/// Полное стирание данных пользователя («Очистить всё» в «Настройках»).
abstract interface class DataEraser {
  /// Стирает операции, переводы, счета и категории (с подкатегориями) и
  /// создаёт стандартный набор категорий заново. Настройки не трогает.
  ///
  /// Всё или ничего: при ошибке прежние данные остаются на месте.
  Future<void> eraseAll();
}
