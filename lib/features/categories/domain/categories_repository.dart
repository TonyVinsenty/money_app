import 'package:money_app/features/categories/domain/category.dart';
import 'package:money_app/features/categories/domain/category_kind.dart';

/// Хранилище категорий: что можно попросить, но не как это устроено.
///
/// Интерфейс живёт в `domain`, а реализация (на drift) — в `data`. Экраны
/// и правила знают только этот интерфейс, поэтому хранилище можно заменить
/// или подменить в тестах фейком.
///
/// Общие ошибки методов:
/// - `CategoryRuleException` — нарушено правило категории;
/// - `DataCorruptedException` — данные в хранилище испорчены и не
///   превращаются в корректную `Category`.
abstract interface class CategoriesRepository {
  /// Поток «живых» категорий верхнего уровня вида [kind], по `sortOrder`.
  ///
  /// В потоке нет архивных и удалённых категорий. Поток сам выдаёт новый
  /// список после каждой записи.
  Stream<List<Category>> watchTopLevel(CategoryKind kind);

  /// Поток «живых» подкатегорий родителя [parentId], по `sortOrder`.
  ///
  /// В потоке нет архивных и удалённых подкатегорий.
  Stream<List<Category>> watchSubcategories(String parentId);

  /// Поток всех не удалённых категорий и подкатегорий, **включая архивные**.
  ///
  /// Нужен, чтобы показать имя и иконку в старых операциях («История»): их
  /// категория могла уйти в архив. Порядок: по `sortOrder`, затем по времени
  /// создания и `id` (важна не очередность, а полнота списка). Поток сам
  /// выдаёт новый список после каждой записи.
  Stream<List<Category>> watchAll();

  /// Находит категорию по [id] или возвращает `null`.
  ///
  /// Архивные категории возвращаются (они нужны, чтобы показать имя в
  /// старых операциях). Мягко удалённые не возвращаются.
  Future<Category?> findById(String id);

  /// Порядок для новой категории верхнего уровня вида [kind]: на единицу
  /// больше самого большого `sortOrder` среди не удалённых категорий этого
  /// вида, **включая архивные** (номера не должны повторяться); для вида без
  /// категорий — 0.
  ///
  /// Если задан [parentId], считается порядок для новой подкатегории этого
  /// родителя: на единицу больше самого большого `sortOrder` среди не
  /// удалённых подкатегорий именно этого родителя (архивные тоже), для
  /// родителя без подкатегорий — 0. [kind] в этом случае не влияет: вид
  /// подкатегории совпадает с видом родителя.
  ///
  /// Читает сырые строки, а не `Category`: испорченная соседняя строка не
  /// мешает добавить новую категорию.
  Future<int> nextSortOrder(CategoryKind kind, {String? parentId});

  /// Есть ли в хранилище хоть одна строка категорий.
  ///
  /// Учитываются и архивные, и удалённые. Нужна для засева категорий по
  /// умолчанию: пользователь мог всё архивировать, и заново засевать нельзя.
  Future<bool> hasAny();

  /// Сохраняет новую [category].
  ///
  /// Для подкатегории проверяет связь с родителем (`Category.checkParent`):
  /// `CategoryRuleException`, если родитель не верхнего уровня или вид
  /// не совпадает. Если среди не архивных категорий того же вида и уровня уже
  /// есть такое имя (без учёта регистра), бросает `CategoryRuleException` с
  /// правилом `duplicateName`.
  Future<void> create(Category category);

  /// Переименовывает категорию [id] в [newName].
  ///
  /// Имя проходит те же проверки, что и при создании
  /// (`CategoryRuleException`, см. `Category.checkedName`) и проверку на
  /// дубль имени (правило `duplicateName`, как в [create]). Категория должна
  /// существовать и не быть удалённой, иначе `ArgumentError`. Сохранённая
  /// строка не превращается в `Category`, поэтому переименованием можно
  /// починить испорченное имя (пустое или слишком длинное).
  Future<void> rename(String id, String newName);

  /// Переставляет «братьев» — не удалённые категории одного уровня (один
  /// `parentId`) и одного вида.
  ///
  /// [orderedIds] — подмножество «братьев» без повторов; иначе
  /// `ArgumentError` (повтор, неизвестный или удалённый id, id из разных
  /// «семей»). Пустой список ничего не меняет.
  ///
  /// Переданные категории получают `sortOrder` `0..n-1` в заданном порядке.
  /// Остальные не удалённые «братья» (например, архивные, которых нет в
  /// списке) сохраняют прежнее относительное положение и получают номера
  /// `n, n+1, ...`. После вызова порядок в «семье» уникален и непрерывен
  /// `0..m-1`. Записываются только реально изменившиеся строки, поэтому
  /// перестановка «на месте» не даёт события в потоках. Всё в одной
  /// транзакции.
  Future<void> reorder(List<String> orderedIds);

  /// Отправляет категорию [id] в архив.
  ///
  /// Она пропадает из «живых» потоков, но операции по ней остаются целыми.
  Future<void> archive(String id);

  /// Возвращает категорию [id] из архива.
  ///
  /// Если её имя за это время занято другой не архивной категорией того же
  /// вида и уровня, бросает `CategoryRuleException` с правилом `duplicateName`.
  Future<void> restore(String id);
}
