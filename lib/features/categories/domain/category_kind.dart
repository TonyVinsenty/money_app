/// Вид категории: для доходов или для расходов.
///
/// У доходов и расходов разные наборы категорий, поэтому каждая категория
/// принадлежит ровно одному виду. Подкатегория всегда того же вида, что и
/// её родитель.
enum CategoryKind {
  /// Категория для доходов.
  income,

  /// Категория для расходов.
  expense,
}
