import 'package:flutter_test/flutter_test.dart';

/// Даёт настоящей базе в памяти дочитать запрос и дожидается кадров.
///
/// Тап по плитке категории сначала читает подкатегории (`.first` от потока
/// drift), а такое ожидание в фейковом времени виджет-теста само не
/// завершается: нужен глоток настоящего времени (`runAsync`).
///
/// Общего признака «база закончила» у экранов нет (индикатора загрузки нет), а
/// цепочка чтений бывает двойной (подкатегории, затем запись). Поэтому два
/// прохода: пауза по 100 мс настоящего времени и кадр после каждой; так
/// хелпер не зависит от одной короткой паузы на медленной машине.
Future<void> settleDatabase(WidgetTester tester) async {
  for (var pass = 0; pass < 2; pass++) {
    await tester.runAsync(
      () => Future<void>.delayed(const Duration(milliseconds: 100)),
    );
    await tester.pump();
  }
  await tester.pumpAndSettle();
}
